namespace Waterly.Api.Models;

public class WaterIntake
{
    public Guid Id { get; set; }
    public Guid UserId { get; set; }
    public int AmountMl { get; set; }

    // The real moment the water was consumed, stored in UTC.
    public DateTimeOffset ConsumedAt { get; set; }

    // The calendar day this intake belongs to, calculated once from ConsumedAt + TimeZone.
    // Storing it keeps old records on the same day even if the user later changes time zone.
    public DateOnly LocalDate { get; set; }

    // IANA time zone that was used to calculate LocalDate.
    public string TimeZone { get; set; } = string.Empty;

    // Generated by the mobile app. Makes "add water" requests idempotent.
    public Guid ClientEventId { get; set; }

    // Manual (default) or ReminderNotification ("I drank" action on a reminder). Used only for achievements.
    public IntakeSource Source { get; set; } = IntakeSource.Manual;

    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }

    public User User { get; set; } = null!;
}
